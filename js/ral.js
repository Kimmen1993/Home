export function ralSearch(q) { q = String(q).trim().toLowerCase().replace(/^ral\s*/, ''); if (!q) return []; return RAL.filter(r => r.code.slice(4).startsWith(q) || r.name.toLowerCase().includes(q)).slice(0, 8); }
